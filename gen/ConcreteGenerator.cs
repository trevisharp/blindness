using System.Linq;
using System.Text;
using System.Collections.Generic;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Blindness.Generators;

/// <summary>
/// Generates at compile time the concrete classes of the interfaces that inherit from INode.
/// </summary>
[Generator]
public class ConcreteGenerator : IIncrementalGenerator
{
    const string nodeInterface = "Blindness.Core.INode";
    const string ignoreAttribute = "Blindness.Factory.IgnoreAttribute";
    const string concreteBaseAttribute = "Blindness.Core.ConcreteBaseAttribute";
    const string defaultBase = "global::Blindness.Core.Node";

    static readonly SymbolDisplayFormat typeFormat = SymbolDisplayFormat.FullyQualifiedFormat
        .WithMiscellaneousOptions(
            SymbolDisplayMiscellaneousOptions.UseSpecialTypes |
            SymbolDisplayMiscellaneousOptions.EscapeKeywordIdentifiers);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.SyntaxProvider
            .CreateSyntaxProvider(
                static (node, _) => node is InterfaceDeclarationSyntax declaration && declaration.BaseList is not null,
                static (ctx, _) => Generate(ctx.SemanticModel.GetDeclaredSymbol(ctx.Node) as INamedTypeSymbol))
            .Where(static file => file.HasValue)
            .Select(static (file, _) => file.Value)
            .Collect();

        context.RegisterSourceOutput(files, static (output, generated) =>
        {
            foreach (var file in generated.GroupBy(f => f.HintName).Select(g => g.First()))
                output.AddSource(file.HintName, SourceText.From(file.Code, Encoding.UTF8));
        });
    }

    /// <summary>
    /// Generate the concrete class of a node interface, or null when the type is not a node.
    /// </summary>
    public static (string HintName, string Code)? Generate(INamedTypeSymbol node)
    {
        if (node is null || node.TypeKind != TypeKind.Interface)
            return null;

        if (node.IsGenericType || node.ContainingType is not null)
            return null;

        if (!node.AllInterfaces.Any(i => i.ToDisplayString() == nodeInterface))
            return null;

        if (HasAttribute(node, ignoreAttribute))
            return null;

        List<INamedTypeSymbol> types = [ node, ..node.AllInterfaces ];
        var nodeName = node.ToDisplayString(typeFormat);
        var className = $"{node.Name}Concrete";
        var access = node.DeclaredAccessibility == Accessibility.Public ? "public" : "internal";

        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/>");
        code.AppendLine("#nullable disable");
        if (!node.ContainingNamespace.IsGlobalNamespace)
            code.AppendLine($"namespace {node.ContainingNamespace.ToDisplayString()};");
        code.AppendLine();
        code.AppendLine("[global::Blindness.Core.Concrete]");
        code.AppendLine($"{access} partial class {className} : {GetBaseClass(types)}, {nodeName}");
        code.AppendLine("{");
        code.AppendLine($"    public {className}() {{ }}");

        AppendDeps(code, types);
        AppendCall(code, types, nodeName, "OnLoad", "Load", false);
        AppendCall(code, types, nodeName, "OnRun", "Run", false);
        AppendCall(code, types, nodeName, "OnUnload", "Unload", true);
        AppendProperties(code, types);

        code.AppendLine("}");

        var hintName = node.ToDisplayString().Replace('<', '_').Replace('>', '_');
        return ($"{hintName}Concrete.g.cs", code.ToString());
    }

    static string GetBaseClass(List<INamedTypeSymbol> types)
    {
        foreach (var type in types)
        {
            var attribute = type.GetAttributes()
                .FirstOrDefault(a => a.AttributeClass?.ToDisplayString() == concreteBaseAttribute);
            if (attribute is not null && attribute.ConstructorArguments.Length == 1
                && attribute.ConstructorArguments[0].Value is ITypeSymbol baseType)
                return baseType.ToDisplayString(typeFormat);
        }

        return defaultBase;
    }

    static void AppendDeps(StringBuilder code, List<INamedTypeSymbol> types)
    {
        var deps = types
            .SelectMany(t => t.GetMembers("Deps").OfType<IMethodSymbol>())
            .FirstOrDefault(m => m.IsAbstract);
        if (deps is null)
            return;

        var parameters = string.Join(", ", deps.Parameters
            .Select(p => $"{p.Type.ToDisplayString(typeFormat)} @{p.Name}"));
        code.AppendLine($"    public void Deps({parameters})");
        code.AppendLine("    {");
        foreach (var parameter in deps.Parameters)
            code.AppendLine($"        this.@{parameter.Name} = @{parameter.Name};");
        code.AppendLine("    }");
    }

    static void AppendCall(StringBuilder code, List<INamedTypeSymbol> types, string nodeName, string method, string target, bool callBase)
    {
        var found = types
            .SelectMany(t => t.GetMembers(method).OfType<IMethodSymbol>())
            .Any(m => m.Parameters.Length == 0 && !m.IsStatic);
        if (!found)
            return;

        if (!callBase)
        {
            code.AppendLine($"    public override void {target}() => (({nodeName})this).{method}();");
            return;
        }

        code.AppendLine($"    public override void {target}()");
        code.AppendLine("    {");
        code.AppendLine($"        (({nodeName})this).{method}();");
        code.AppendLine($"        base.{target}();");
        code.AppendLine("    }");
    }

    static void AppendProperties(StringBuilder code, List<INamedTypeSymbol> types)
    {
        var properties = types
            .SelectMany(t => t.GetMembers().OfType<IPropertySymbol>())
            .Where(p => !p.IsStatic && !p.IsIndexer && p.IsAbstract)
            .GroupBy(p => p.Name)
            .Select(g => g.First());

        foreach (var property in properties)
        {
            var type = property.Type.ToDisplayString(typeFormat);
            var field = $"__{property.Name}Box";
            var box = $"({field} ??= global::Blindness.Bind.Binding.Get(this).Dictionary.GetOrCreate<{type}>(nameof({property.Name})))";
            code.AppendLine($"    global::Blindness.Bind.IBox<{type}, {type}> {field};");
            code.AppendLine("    [global::Blindness.Bind.Binding]");
            code.AppendLine($"    public {type} {property.Name}");
            code.AppendLine("    {");
            code.AppendLine($"        get => {box}.Open();");
            code.AppendLine($"        set => {box}.Place(value);");
            code.AppendLine("    }");
        }
    }

    static bool HasAttribute(INamedTypeSymbol type, string attributeName)
        => type.GetAttributes().Any(a => a.AttributeClass?.ToDisplayString() == attributeName);
}
